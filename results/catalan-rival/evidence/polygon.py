#!/usr/bin/env python3
r"""Polygon picture and vanishing-sums analysis for S_i at a root of unity.

Everything is exact integer arithmetic in Z[x]/(x^k - 1), with vanishing tested by
divisibility by Phi_k in Z[x]. No floating point enters any decision.

Contents
    expand(word)          signed exponent expansion of S_i as a Laurent polynomial
    term_count(word)      number of monomials with multiplicity (ordinary continuant)
    vec(word, k)          the expansion folded into Z^{Z/k}
    is_zero(word, k)      Phi_k | S_i test
    locus(k, length)      exact vanishing locus
    decompose(a, k)       explicit integer decomposition into rotated p-gon relations
    fold(a, k, l)         reduction of the relation vector to level l
    main()                all reported checks

Run:
    python3 polygon.py
"""

from __future__ import annotations

import itertools
import json
from collections import Counter
from pathlib import Path

import sympy
from sympy import Poly, cyclotomic_poly, symbols

x = symbols("x")

# ----------------------------------------------------------------------------------
# 1. The expansion
# ----------------------------------------------------------------------------------


def matchings(n: int):
    """All matchings of the path on vertices 0..n-1, as tuples of left endpoints."""
    if n <= 1:
        yield ()
        return
    for m in matchings(n - 1):
        yield m
    for m in matchings(n - 2):
        yield m + (n - 2,)


def expand(word):
    """S_i for word = (c_2, ..., c_i) as a Counter on integer exponents.

    S_i = sum over matchings M of the path c_2 - c_3 - ... - c_i of
          (-1)^|M| prod_{(j-1,j) in M} q^{c_{j-1} - 1} prod_{j unmatched} [c_j]_q.

    Every c_j is used as a literal integer, so the exponents are literal.
    """
    n = len(word)
    out = Counter()
    for M in matchings(n):
        left = set(M)
        matched = left | {j + 1 for j in M}
        sign = (-1) ** len(M)
        base = sum(word[j] - 1 for j in M)
        free = [j for j in range(n) if j not in matched]
        # product of [c_j]_q over free j, as an exponent-set convolution
        acc = Counter({base: sign})
        for j in free:
            nxt = Counter()
            for e, v in acc.items():
                for t in range(word[j]):
                    nxt[e + t] += v
            acc = nxt
        out.update(acc)
    return Counter({e: v for e, v in out.items() if v})


def term_count(word):
    """Monomials with multiplicity, i.e. the ordinary continuant K(c_2, ..., c_i)."""
    a, b = 1, 0  # K of empty word, K of the word one shorter still
    for c in word:
        a, b = c * a + b, a
    return a


def signed_term_count(word):
    """Positive and negative monomial counts, with multiplicity."""
    n = len(word)
    pos = neg = 0
    for M in matchings(n):
        matched = set(M) | {j + 1 for j in M}
        prod = 1
        for j in range(n):
            if j not in matched:
                prod *= word[j]
        if len(M) % 2 == 0:
            pos += prod
        else:
            neg += prod
    return pos, neg


# ----------------------------------------------------------------------------------
# 2. Vanishing
# ----------------------------------------------------------------------------------


def rep(c, k):
    """Representative in {1, ..., k} of c mod k. Value of S_i is unchanged."""
    r = c % k
    return k if r == 0 else r


def vec(word, k):
    """The expansion of S_i folded into Z^{Z/k}."""
    a = [0] * k
    for e, v in expand(word).items():
        a[e % k] += v
    return a


def poly_of(a):
    return Poly(list(reversed(a)), x, domain="ZZ")


_PHI = {}


def phi(k):
    if k not in _PHI:
        _PHI[k] = Poly(cyclotomic_poly(k, x), x, domain="ZZ")
    return _PHI[k]


def is_zero(word, k):
    """True iff S_i(omega_k) = 0, tested as Phi_k | S_i in Z[x]."""
    a = vec([rep(c, k) for c in word], k)
    if not any(a):
        return True
    return poly_of(a).rem(phi(k)).is_zero


def locus(k, length):
    """Every residue word (c_2, ..., c_length) in (Z/k)^{length-1} with S(omega_k) = 0."""
    return [w for w in itertools.product(range(k), repeat=length - 1) if is_zero(w, k)]


# ----------------------------------------------------------------------------------
# 3. Decomposition into rotated p-gon relations
# ----------------------------------------------------------------------------------
#
# Redei, de Bruijn, Schoenberg: the kernel of Z[x]/(x^k - 1) -> Z[zeta_k] is the ideal
# generated by Phi_p(x^{k/p}) for the primes p dividing k. So every vanishing sum of
# kth roots with integer coefficients is an integer combination of the rotated regular
# p-gons
#       R_p(t) = sum_{j=0}^{p-1} x^{t + j k / p},        p | k,  t in Z/k.
#
# The reduction below is constructive. Write k = prod p^a. By CRT an exponent e is a
# tuple of digits, and R_p(t) shifts only the top digit in the p coordinate, so
# eliminating that digit prime by prime terminates and never disturbs a finished prime.


def prime_powers(k):
    return [(p, a) for p, a in sympy.factorint(k).items()]


def decompose(a, k):
    """Return (components, residual).

    components is a list of (p, t, coefficient) with
        a == sum coefficient * R_p(t)   +   residual,
    and residual is zero exactly when a is a vanishing sum.
    """
    a = list(a)
    comps = []
    for p, e in prime_powers(k):
        step = k // p              # R_p(t) hits t, t + step, ..., t + (p-1) step
        pe = p ** e
        top = pe // p              # digit_p(n) = (n mod p^e) // p^{e-1}
        u = (step // top) % p      # adding step raises the digit by the unit u
        jstar = ((p - 1) * pow(u, -1, p)) % p
        for t in range(k):
            if (t % pe) // top != p - 1:
                continue
            c = a[t]
            if c == 0:
                continue
            base = (t - jstar * step) % k
            assert (base % pe) // top == 0
            for j in range(p):
                a[(base + j * step) % k] -= c
            comps.append((p, base, c))
    return comps, a


def fold(a, k, l):
    """Reduce a relation vector at level k to level l, for l dividing k."""
    b = [0] * l
    for e, v in enumerate(a):
        b[e % l] += v
    return b


def component_folds(comps, k, l):
    """Split components by whether folding to level l kills them.

    R_p(t) folded to level l is 0 if l does not divide k/p, and p * x^{t mod l} if it
    does. So a component survives exactly when v_p(l) = v_p(k).
    """
    surviving, dying = [], [0] * l
    for p, t, c in comps:
        if (k // p) % l == 0:
            dying[t % l] += c * p
        else:
            surviving.append((p, t, c))
    return surviving, dying


